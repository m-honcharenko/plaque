// Generates src/core/text/metrics.data.ts: advance widths of Inter for
// Latin and Cyrillic at weights 400 and 600, in thousandths of an em.
// Run: bun run fonts:generate
//
// The font is only read here (devDependency). It is a stand-in for the
// reader's system font, so an estimate is all we need: textLength in the
// SVG absorbs the rest. Kerning is ignored on purpose.
import { readFileSync, mkdirSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"

const require = createRequire(import.meta.url)

type Glyph = { advanceWidth?: number }
type Font = {
	unitsPerEm: number
	tables: { cmap: { glyphIndexMap: Record<string, number> } }
	glyphs: { get(index: number): Glyph }
}
const opentype = require("opentype.js") as {
	parse(buffer: ArrayBuffer): Font
}

const WEIGHTS = [400, 600] as const
// Order matters: the first subset that has a character wins.
const SUBSETS = ["latin", "latin-ext", "cyrillic", "cyrillic-ext"] as const

function load(subset: string, weight: number): Font {
	const file = readFileSync(
		`node_modules/@fontsource/inter/files/inter-${subset}-${weight}-normal.woff`
	)
	const bytes = file.buffer.slice(
		file.byteOffset,
		file.byteOffset + file.byteLength
	) as ArrayBuffer
	return opentype.parse(bytes)
}

const widths: Record<number, Record<number, number>> = {}
const fallback: Record<number, number> = {}

for (const weight of WEIGHTS) {
	const table: Record<number, number> = {}
	for (const subset of SUBSETS) {
		const font = load(subset, weight)
		for (const [code, index] of Object.entries(
			font.tables.cmap.glyphIndexMap
		)) {
			const cp = Number(code)
			// Skip control characters and anything outside the BMP: those fall
			// back to class widths in measure().
			if (cp < 0x20 || (cp >= 0x7f && cp < 0xa0) || cp > 0xffff) continue
			if (table[cp] !== undefined) continue
			const advance = font.glyphs.get(index).advanceWidth
			if (advance === undefined) continue
			table[cp] = Math.round((advance / font.unitsPerEm) * 1000)
		}
	}
	// Average width of ASCII letters: the guess for characters we lack.
	const letters = [...Array(26).keys()].flatMap((i) => [97 + i, 65 + i])
	const sum = letters.reduce((acc, cp) => acc + (table[cp] ?? 0), 0)
	fallback[weight] = Math.round(sum / letters.length)
	widths[weight] = table
}

function render(table: Record<number, number>): string {
	return Object.keys(table)
		.map(Number)
		.sort((a, b) => a - b)
		.map((cp) => `${cp}:${table[cp]}`)
		.join(",")
}

mkdirSync("src/core/text", { recursive: true })
writeFileSync(
	"src/core/text/metrics.data.ts",
	`// GENERATED by scripts/gen-font-metrics.ts. Do not edit.
// Inter advance widths in thousandths of an em, keyed by code point.
import type { FontMetrics } from "./measure.js"

export const FONT_METRICS: FontMetrics = {
	fallback: { 400: ${fallback[400]}, 600: ${fallback[600]} },
	widths: {
		400: { ${render(widths[400]!)} },
		600: { ${render(widths[600]!)} }
	}
}
`
)

console.log(
	`Wrote ${Object.keys(widths[400]!).length} widths per weight, fallback`,
	fallback
)
