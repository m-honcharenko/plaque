// Generates src/core/icons/icons.data.ts and THIRD_PARTY_LICENSES.md from
// the icon packages. Run: bun run icons:generate
//
// The packages are devDependencies only: the whitelist below decides which
// paths are copied into the repo, so the runtime never loads a whole set.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"

const require = createRequire(import.meta.url)

type Octicon = { heights: Record<string, { path: string }> }
type SimpleIcon = { path: string; slug: string }

const octicons = require("@primer/octicons") as Record<string, Octicon>
const simpleIcons = require("simple-icons") as Record<string, SimpleIcon>

// Status and UI icons (Octicons, 16px grid).
const UI = [
	"alert",
	"bug",
	"check",
	"check-circle",
	"clock",
	"code",
	"download",
	"eye",
	"git-branch",
	"git-pull-request",
	"heart",
	"info",
	"law",
	"package",
	"repo",
	"rocket",
	"shield-check",
	"skip",
	"star",
	"stop",
	"sync",
	"tag",
	"workflow",
	"x",
	"x-circle"
]

// Brand icons (Simple Icons, 24px grid). Slugs are the export names
// without the "si" prefix, lowercased.
const BRANDS = [
	"apple",
	"bitbucket",
	"bun",
	"codeberg",
	"docker",
	"fastify",
	"github",
	"gitlab",
	"linux",
	"nestjs",
	"npm",
	"swift",
	"typescript"
]

// Only path data of this shape ever reaches an SVG attribute.
const PATH_DATA = /^[MmLlHhVvCcSsQqTtAaZz0-9eE.,\s-]+$/

type Entry = { size: 16 | 24; d: string }
const entries = new Map<string, Entry>()

function add(name: string, entry: Entry): void {
	if (entries.has(name)) throw new Error(`Duplicate icon name: ${name}`)
	if (!PATH_DATA.test(entry.d)) throw new Error(`Unsafe path data: ${name}`)
	entries.set(name, entry)
}

for (const name of UI) {
	const markup = octicons[name]?.heights["16"]?.path
	if (markup === undefined) throw new Error(`Octicon not found: ${name}`)
	// Accept only plain <path d="..."/> elements, joined into one path:
	// anything else (fill-rule, circles, groups) would need real handling,
	// so fail loudly instead of dropping it silently.
	const plain = /<path d="([^"]+)"><\/path>/g
	const parts = [...markup.matchAll(plain)].map((m) => m[1])
	if (parts.length === 0 || markup.replace(plain, "") !== "") {
		throw new Error(`Octicon ${name} is not plain paths only: ${markup}`)
	}
	add(name, { size: 16, d: parts.join(" ") })
}

for (const slug of BRANDS) {
	const icon = Object.values(simpleIcons).find((i) => i.slug === slug)
	if (icon === undefined) throw new Error(`Simple icon not found: ${slug}`)
	add(slug, { size: 24, d: icon.path })
}

const names = [...entries.keys()].sort()
const body = names
	.map((name) => {
		const e = entries.get(name)!
		return `\t${JSON.stringify(name)}: { size: ${e.size}, d: ${JSON.stringify(e.d)} }`
	})
	.join(",\n")

mkdirSync("src/core/icons", { recursive: true })

writeFileSync(
	"src/core/icons/icons.data.ts",
	`// GENERATED by scripts/gen-icons.ts. Do not edit: change the whitelist there.
import type { IconData } from "./icons.js"

export const ICON_DATA = {
${body}
} as const satisfies Record<string, IconData>
`
)

const license = (pkg: string) =>
	readFileSync(`node_modules/${pkg}/LICENSE`, "utf8").trim()
const version = (pkg: string) =>
	(
		JSON.parse(readFileSync(`node_modules/${pkg}/package.json`, "utf8")) as {
			version: string
		}
	).version

writeFileSync(
	"THIRD_PARTY_LICENSES.md",
	`# Third-party licenses

The icon paths in \`src/core/icons/icons.data.ts\` are copied from the packages
below. Regenerate with \`bun run icons:generate\`.

## Octicons (@primer/octicons ${version("@primer/octicons")}), MIT

${license("@primer/octicons")}

## Simple Icons (simple-icons ${version("simple-icons")}), CC0-1.0

Brand icons are public domain as artwork, but the brands themselves are
trademarks of their owners. See the Simple Icons legal disclaimer:
https://github.com/simple-icons/simple-icons/blob/develop/DISCLAIMER.md
`
)

console.log(`Wrote ${names.length} icons`)
